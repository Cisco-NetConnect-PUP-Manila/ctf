param(
  [switch]$Attached,
  [switch]$NoBuild,
  [switch]$NoMigrate,
  [switch]$AutoPorts
)

$ErrorActionPreference = "Stop"

$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$envPath = Join-Path $root ".env"

function Read-EnvFile {
  param([string]$Path)

  $values = @{}
  if (-not (Test-Path -LiteralPath $Path)) {
    return $values
  }

  foreach ($line in Get-Content -LiteralPath $Path) {
    $trimmed = $line.Trim()
    if (-not $trimmed -or $trimmed.StartsWith("#") -or -not $trimmed.Contains("=")) {
      continue
    }

    $parts = $trimmed.Split("=", 2)
    $values[$parts[0]] = $parts[1]
  }

  return $values
}

function Get-UsedTcpPorts {
  [System.Net.NetworkInformation.IPGlobalProperties]::GetIPGlobalProperties().
    GetActiveTcpListeners() |
    ForEach-Object { $_.Port } |
    Sort-Object -Unique
}

function Get-AvailablePort {
  param([int[]]$PreferredPorts)

  $used = @(Get-UsedTcpPorts)
  foreach ($port in $PreferredPorts) {
    if ($used -notcontains $port) {
      return $port
    }
  }

  $listener = [System.Net.Sockets.TcpListener]::new([System.Net.IPAddress]::Loopback, 0)
  try {
    $listener.Start()
    return $listener.LocalEndpoint.Port
  }
  finally {
    $listener.Stop()
  }
}

function Get-EnvValue {
  param(
    [hashtable]$Values,
    [string]$Key,
    [string]$Default
  )

  if ($Values.ContainsKey($Key) -and $Values[$Key]) {
    return $Values[$Key]
  }

  return $Default
}

$existing = Read-EnvFile -Path $envPath

if ($AutoPorts) {
  $frontendPort = Get-AvailablePort @(3001, 3000, 3002, 3003, 3100)
  $backendPort = Get-AvailablePort @(8001, 8000, 8002, 8003, 8100)
  $postgresPort = Get-AvailablePort @(5433, 5432, 5434, 55432)
}
else {
  $frontendPort = 3001
  $backendPort = 8001
  $postgresPort = 5433
}

$postgresDb = Get-EnvValue $existing "POSTGRES_DB" "packet_capture_ctf"
$postgresUser = Get-EnvValue $existing "POSTGRES_USER" "packet_capture"
$postgresPassword = Get-EnvValue $existing "POSTGRES_PASSWORD" "packet_capture_local_password"
$sessionCookieName = Get-EnvValue $existing "SESSION_COOKIE_NAME" "packet_capture_session"
$sessionCookieSecure = Get-EnvValue $existing "SESSION_COOKIE_SECURE" "false"
$sessionExpireHours = Get-EnvValue $existing "SESSION_EXPIRE_HOURS" "12"
$registrationOpen = Get-EnvValue $existing "REGISTRATION_OPEN_BY_DEFAULT" "true"

$envContent = @(
  "# Generated by scripts/docker-dev.ps1"
  "# Safe to edit locally. This file is ignored by git."
  "FRONTEND_PORT=$frontendPort"
  "NEXT_PUBLIC_API_BASE_URL=http://localhost:$backendPort"
  ""
  "BACKEND_PORT=$backendPort"
  "BACKEND_ENV=local"
  "FRONTEND_ORIGIN=http://localhost:$frontendPort"
  "SESSION_COOKIE_NAME=$sessionCookieName"
  "SESSION_COOKIE_SECURE=$sessionCookieSecure"
  "SESSION_EXPIRE_HOURS=$sessionExpireHours"
  "REGISTRATION_OPEN_BY_DEFAULT=$registrationOpen"
  ""
  "POSTGRES_DB=$postgresDb"
  "POSTGRES_USER=$postgresUser"
  "POSTGRES_PASSWORD=$postgresPassword"
  "POSTGRES_PORT=$postgresPort"
  ""
  "DATABASE_URL=postgresql+psycopg://$postgresUser`:$postgresPassword@localhost:$postgresPort/$postgresDb"
  "DOCKER_DATABASE_URL=postgresql+psycopg://$postgresUser`:$postgresPassword@postgres:5432/$postgresDb"
)

Set-Content -LiteralPath $envPath -Value $envContent -Encoding UTF8

Write-Host "Packet Capture Docker environment configured:"
Write-Host "  Frontend:  http://localhost:$frontendPort"
Write-Host "  Backend:   http://localhost:$backendPort/docs"
Write-Host "  Postgres:  localhost:$postgresPort"
if (-not $AutoPorts) {
  Write-Host "  Mode:      fixed team ports"
}
else {
  Write-Host "  Mode:      auto-selected open ports"
}
Write-Host ""

$composeArgs = @("up")
if (-not $Attached) {
  $composeArgs += "-d"
}
if (-not $NoBuild) {
  $composeArgs += "--build"
}

Push-Location $root
try {
  & docker-compose @composeArgs
  if ($LASTEXITCODE -ne 0) {
    exit $LASTEXITCODE
  }

  if (-not $NoMigrate) {
    & docker-compose exec -T backend alembic upgrade head
    if ($LASTEXITCODE -ne 0) {
      exit $LASTEXITCODE
    }
  }
}
finally {
  Pop-Location
}
